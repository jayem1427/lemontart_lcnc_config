#!/usr/bin/env bash
# Install what drive homing (docs/DRIVE_HOMING.md, test D1) needs, for one or both LinuxCNC builds:
#   - linuxcnc-ethercat v1.49.0: lcec + its in-tree `cia402` (replaces lcec v1.41 and the old
#     halcompile'd hal-cia402 `cia402.so`). Pins used by ethercat_mill.hal need this version.
#   - cia402_homecomp, the HOMEMOD ([EMCMOT]HOMEMOD = cia402_homecomp). It #includes the
#     homing.c of the LinuxCNC it runs under, so it is built once per LinuxCNC build.
#
# Usage:
#   scripts/install-drive-homing.sh            # stock apt 2.9.8 (asks for sudo) and tpnext RIP
#   scripts/install-drive-homing.sh stock      # launch.sh only
#   scripts/install-drive-homing.sh tpnext     # launch-tpnext.sh only (no sudo)
#
# Run with LinuxCNC closed. Old modules are copied to ~/drive-homing-backup/<time>/ first.
# Rollback: copy those files back (sudo for /usr/lib/linuxcnc/modules), or
#   git -C ~/linuxcnc-ethercat checkout "$(cat ~/drive-homing-backup/<time>/lcec_prev_head)"
#   and rebuild lcec as docs/SETUP.md describes. HOMEMOD must also come out of the INI.
set -euo pipefail

LCEC_TAG=v1.49.0
HOMECOMP_COMMIT=b13bf72221ba38dfee9e299e8b64587caa29cec2
LCEC_DIR="${LCEC_DIR:-$HOME/linuxcnc-ethercat}"
HC_DIR="${HC_DIR:-$HOME/src/cia402_homecomp}"
RIP="${LINUXCNC_TPNEXT_RIP:-/home/jon/src/linuxcnc-tpnext}"
DEPS="${LINUXCNC_TPNEXT_DEPS:-/home/jon/src/deps-prefix}"
STOCK_MODULES=/usr/lib/linuxcnc/modules
WHAT="${1:-all}"
case "$WHAT" in all|stock|tpnext) ;; *) echo "usage: $0 [all|stock|tpnext]" >&2; exit 2 ;; esac

BACKUP="$HOME/drive-homing-backup/$(date +%Y%m%d-%H%M%S)"
die() { echo "ERROR: $*" >&2; exit 1; }

if pgrep -x rtapi_app >/dev/null || pgrep -x milltask >/dev/null; then
  die "LinuxCNC is running. Close it first."
fi

# ---------- sources ----------
[[ -d "$LCEC_DIR/.git" ]] || die "$LCEC_DIR is not a linuxcnc-ethercat git checkout (set LCEC_DIR=...)"
if [[ -n "$(git -C "$LCEC_DIR" status --porcelain --untracked-files=no)" ]]; then
  die "$LCEC_DIR has local changes. Commit or stash them first:  git -C $LCEC_DIR status"
fi
mkdir -p "$BACKUP"
git -C "$LCEC_DIR" rev-parse HEAD > "$BACKUP/lcec_prev_head"
git -C "$LCEC_DIR" fetch --tags origin
git -C "$LCEC_DIR" checkout -q "$LCEC_TAG"
echo "linuxcnc-ethercat: $(git -C "$LCEC_DIR" describe --tags) (was $(cut -c1-9 "$BACKUP/lcec_prev_head"))"

if [[ ! -d "$HC_DIR/.git" ]]; then
  mkdir -p "$(dirname "$HC_DIR")"
  git clone https://github.com/linuxcnc-ethercat/cia402_homecomp.git "$HC_DIR"
fi
git -C "$HC_DIR" fetch origin
git -C "$HC_DIR" checkout -q "$HOMECOMP_COMMIT"
echo "cia402_homecomp: $(git -C "$HC_DIR" rev-parse --short HEAD)"

# Copy comp + headers + generated homing_config.h into a fresh build dir ($1 = dir, $2 = homing.c, $3 = homing.h)
stage_homecomp() {
  local b="$1"
  rm -rf "$b"; mkdir -p "$b"
  cp "$HC_DIR/cia402_homecomp.comp" "$HC_DIR/cia402_homecomp.h" "$LCEC_DIR/src/lcec_hal_compat.h" "$b/"
  {
    echo "/* Generated by lemontart scripts/install-drive-homing.sh */"
    echo "#define HOMING_BASE $2"
    if grep -q 'double home_search_dist' "$3"; then echo '#define CIA402_HOMING_HAS_DISTANCES 1'; fi
  } > "$b/homing_config.h"
}

# ---------- stock apt LinuxCNC (launch.sh) ----------
install_stock() {
  echo "=== stock LinuxCNC ==="
  command -v halcompile >/dev/null || die "halcompile missing: sudo apt install linuxcnc-uspace-dev"
  [[ -f /usr/include/linuxcnc/homing.h ]] || die "/usr/include/linuxcnc/homing.h missing: sudo apt install linuxcnc-uspace-dev"
  local ver
  ver="$(dpkg-query -W -f='${Version}' linuxcnc-uspace 2>/dev/null | sed 's/^[0-9]*://; s/[-+~].*//')"
  [[ -n "$ver" ]] || die "can't read the linuxcnc-uspace package version"
  echo "apt LinuxCNC $ver"

  mkdir -p "$BACKUP/stock"
  for f in lcec.so cia402.so cia402_homecomp.so; do
    if [[ -f "$STOCK_MODULES/$f" ]]; then cp -p "$STOCK_MODULES/$f" "$BACKUP/stock/"; fi
  done
  if [[ -f /usr/bin/lcec_conf ]]; then cp -p /usr/bin/lcec_conf "$BACKUP/stock/"; fi

  ( # clean environment: no RIP variables, or lcec's configure picks the wrong tree
    unset LINUXCNC_HOME EMC2_HOME
    cd "$LCEC_DIR"
    make clean
    make
    sudo make install
  )

  # homing.c is not in the apt packages; fetch the one matching the installed version.
  local b="$HOME/src/cia402_homecomp-build-stock"
  mkdir -p "$b.src"
  curl -fsSL -o "$b.src/homing.c" "https://raw.githubusercontent.com/LinuxCNC/linuxcnc/v$ver/src/emc/motion/homing.c" \
    || die "could not download homing.c for v$ver"
  stage_homecomp "$b" "$b.src/homing.c" /usr/include/linuxcnc/homing.h
  sudo halcompile --install "$b/cia402_homecomp.comp"
  ls -l "$STOCK_MODULES/lcec.so" "$STOCK_MODULES/cia402.so" "$STOCK_MODULES/cia402_homecomp.so"
}

# ---------- tpnext-ma run-in-place build (launch-tpnext.sh) ----------
install_tpnext() {
  echo "=== tpnext RIP: $RIP ==="
  [[ -f "$RIP/scripts/rip-environment" ]] || die "tpnext RIP not found at $RIP"
  [[ -f "$RIP/src/emc/motion/homing.c" ]] || die "$RIP/src/emc/motion/homing.c missing"

  mkdir -p "$BACKUP/tpnext"
  for f in lcec.so cia402.so cia402_homecomp.so; do
    if [[ -f "$RIP/rtlib/$f" ]]; then cp -p "$RIP/rtlib/$f" "$BACKUP/tpnext/"; fi
  done
  if [[ -f "$RIP/bin/lcec_conf" ]]; then cp -p "$RIP/bin/lcec_conf" "$BACKUP/tpnext/"; fi

  ( export LD_LIBRARY_PATH="${DEPS}/usr/lib/x86_64-linux-gnu${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
    set +u
    # shellcheck disable=SC1091
    source "$RIP/scripts/rip-environment"
    set -u
    cd "$LCEC_DIR"
    make clean
    make
    make install-rip LINUXCNC_HOME="$RIP"

    local b="$HOME/src/cia402_homecomp-build-tpnext"
    stage_homecomp "$b" "$RIP/src/emc/motion/homing.c" "$RIP/src/emc/motion/homing.h"
    halcompile --install "$b/cia402_homecomp.comp"
  )
  ls -l "$RIP/rtlib/lcec.so" "$RIP/rtlib/cia402.so" "$RIP/rtlib/cia402_homecomp.so"
}

# Stock first, tpnext last: each starts with `make clean`, and the lcec tree is left built for tpnext.
if [[ "$WHAT" == all || "$WHAT" == stock ]]; then install_stock; fi
if [[ "$WHAT" == all || "$WHAT" == tpnext ]]; then install_tpnext; fi

echo
echo "Done. Backups and the previous lcec commit are in $BACKUP"
echo "Next: docs/DRIVE_HOMING.md test D1 (load check with the machine OFF, then jog before any homing)."
