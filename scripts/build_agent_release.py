#!/usr/bin/env python3
"""Build release/lemontart-agent from agent/ skills and docs/.

The release folder is what we ship: skills plus the markdown guides they
route to. Vendor files in docs/reference/ stay in the config repo.
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "agent"
DOCS = ROOT / "docs"
OUT = ROOT / "release" / "lemontart-agent"
SKIP_DOC_DIRS = {"reference"}


def _copy_tree(src: Path, dest: Path) -> None:
    if src.is_dir():
        shutil.copytree(src, dest)
    else:
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dest)


def assemble(dest: Path) -> None:
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)

    version = (SRC / "VERSION").read_text(encoding="utf-8").strip()
    readme = (SRC / "README.md").read_text(encoding="utf-8")
    banner = (
        f"<!-- Generated by scripts/build_agent_release.py from agent/ and docs/. "
        f"Version {version}. Do not edit this copy. -->\n\n"
    )
    (dest / "VERSION").write_text(version + "\n", encoding="utf-8")
    (dest / "README.md").write_text(banner + readme, encoding="utf-8")

    for skill in sorted(p for p in (SRC).iterdir() if p.is_dir()):
        _copy_tree(skill, dest / "skills" / skill.name)

    docs_out = dest / "docs"
    docs_out.mkdir()
    for path in sorted(DOCS.iterdir()):
        if path.name in SKIP_DOC_DIRS:
            continue
        if path.suffix == ".md" or path.is_dir():
            _copy_tree(path, docs_out / path.name)

    names = sorted(
        p.relative_to(dest).as_posix()
        for p in dest.rglob("*")
        if p.is_file() and p.name != "MANIFEST.txt"
    )
    manifest = [f"lemontart-agent {version}", ""] + names + [""]
    (dest / "MANIFEST.txt").write_text("\n".join(manifest), encoding="utf-8")


def _files(root: Path) -> dict[str, bytes]:
    return {
        path.relative_to(root).as_posix(): path.read_bytes()
        for path in root.rglob("*")
        if path.is_file()
    }


def _same_tree(a: Path, b: Path) -> bool:
    return _files(a) == _files(b)


def check() -> int:
    if not OUT.exists():
        print(f"missing {OUT.relative_to(ROOT)} — run without --check", file=sys.stderr)
        return 1
    import tempfile

    with tempfile.TemporaryDirectory() as tmp:
        fresh = Path(tmp) / "lemontart-agent"
        assemble(fresh)
        if _same_tree(OUT, fresh):
            print(f"{OUT.relative_to(ROOT)} matches agent/ and docs/")
            return 0
        print(
            f"{OUT.relative_to(ROOT)} is stale — run python3 scripts/build_agent_release.py",
            file=sys.stderr,
        )
        return 1


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if release/lemontart-agent is missing or out of date",
    )
    args = parser.parse_args()
    if args.check:
        return check()
    assemble(OUT)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
